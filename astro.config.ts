import { defineConfig, envField, svgoOptimizer } from "astro/config";
import tailwindcss from "@tailwindcss/vite";
import mdx from "@astrojs/mdx";
import sitemap from "@astrojs/sitemap";
import { rehypeHeadingIds, unified } from "@astrojs/markdown-remark";
import rehypeCallouts from "rehype-callouts";
import remarkMath from "remark-math";
import rehypeKatex from "rehype-katex";
import rehypeMermaid from "rehype-mermaid";
import {
  transformerNotationDiff,
  transformerNotationHighlight,
  transformerNotationWordHighlight,
} from "@shikijs/transformers";
import brokenLinksChecker from "astro-broken-links-checker";
import { transformerFileName } from "./src/utils/transformers/fileName";
import { rehypeTableWrapper } from "./src/utils/rehypeTableWrapper";
import { rehypeLocalImages } from "./src/utils/rehypeLocalImages";
import { remarkReadingTime } from "./src/utils/remarkReadingTime";
import {
  inlineTocDeprecation,
  rehypeInlineToc,
} from "./src/utils/rehypeInlineToc";
import config from "./astro-paper.config";
import legacy from "./src/data/redirects.json";

// Old Jekyll URLs -> new URLs (see src/data/redirects.json, generated by
// scripts/migrate_posts.py). Astro emits a meta-refresh + canonical page for each.
const redirects: Record<string, string> = {
  ...legacy.posts,
  ...Object.fromEntries(
    Object.entries(legacy.tags).filter(([from, to]) => from !== to)
  ),
};

const mermaidPlugin = [
  rehypeMermaid,
  {
    // Rendered to inline SVG at build time (no client JS). Colours are
    // neutral and finished in CSS (see typography.css) so dark mode follows
    // the site's theme toggle rather than the OS setting.
    strategy: "inline-svg",
    mermaidConfig: {
      theme: "neutral",
      fontFamily: "Arial, Helvetica, sans-serif",
    },
  },
] as never;

export default defineConfig({
  site: config.site.url,
  trailingSlash: "ignore",
  redirects,
  integrations: [
    mdx(),
    sitemap({
      filter: page =>
        config.features?.showArchives !== false || !/\/archives\/?$/.test(page),
    }),
    inlineTocDeprecation(),
    brokenLinksChecker({
      checkExternalLinks: false,
      throwError: true,
    }),
  ],
  i18n: {
    locales: ["en"],
    defaultLocale: "en",
    routing: { prefixDefaultLocale: false },
  },
  markdown: {
    syntaxHighlight: { type: "shiki", excludeLangs: ["mermaid", "math"] },
    processor: unified({
      remarkPlugins: [remarkMath, remarkReadingTime],
      rehypePlugins: [
        rehypeHeadingIds,
        rehypeInlineToc,
        rehypeCallouts,
        rehypeTableWrapper,
        rehypeLocalImages,
        rehypeKatex,
        mermaidPlugin,
      ],
    }),
    shikiConfig: {
      themes: { light: "github-light", dark: "github-dark-dimmed" },
      defaultColor: false,
      wrap: false,
      transformers: [
        transformerFileName({ style: "v2", hideDot: false }),
        transformerNotationHighlight(),
        transformerNotationWordHighlight(),
        transformerNotationDiff({ matchAlgorithm: "v3" }),
      ],
    },
  },
  vite: {
    plugins: [tailwindcss()],
  },
  env: {
    schema: {
      PUBLIC_GOOGLE_SITE_VERIFICATION: envField.string({
        access: "public",
        context: "client",
        optional: true,
      }),
    },
  },
  experimental: {
    svgOptimizer: svgoOptimizer(),
  },
});
